#!/usr/bin/env python3
"""Builds the executive and technical slide decks (.pptx) from the figures
in docs/figures/ (generated by generate_deliverable_assets.py) and the
same numbers reported by the training pipeline, never hand-typed
separately from what the pipeline actually measured.

Usage: python scripts/build_slides.py
Outputs to deliverables/ (gitignored, these are submission artifacts,
not repository content).
"""

from __future__ import annotations

from pathlib import Path

from pptx import Presentation
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from pptx.util import Inches, Pt

from pdm.config import REPO_ROOT, load_config
from pdm.models.bundle import BUNDLE_FILENAME, ModelBundle

FIGURES = REPO_ROOT / "docs" / "figures"
OUT_DIR = REPO_ROOT.parent / "deliverables"
OUT_DIR.mkdir(parents=True, exist_ok=True)

NAVY = RGBColor(0x1F, 0x3A, 0x5F)
GRAY = RGBColor(0x4A, 0x4A, 0x4A)
ACCENT = RGBColor(0x55, 0xA8, 0x68)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)

SLIDE_W, SLIDE_H = Inches(13.333), Inches(7.5)


def new_deck() -> Presentation:
    prs = Presentation()
    prs.slide_width = SLIDE_W
    prs.slide_height = SLIDE_H
    return prs


def blank_slide(prs: Presentation):
    return prs.slides.add_slide(prs.slide_layouts[6])


def add_title(slide, text: str, size: int = 32, color=NAVY, top=Inches(0.4)) -> None:
    box = slide.shapes.add_textbox(Inches(0.6), top, SLIDE_W - Inches(1.2), Inches(1.0))
    tf = box.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = text
    p.font.size = Pt(size)
    p.font.bold = True
    p.font.color.rgb = color


def add_subtitle(slide, text: str, top=Inches(1.2), size=18, color=GRAY) -> None:
    box = slide.shapes.add_textbox(Inches(0.6), top, SLIDE_W - Inches(1.2), Inches(0.6))
    p = box.text_frame.paragraphs[0]
    p.text = text
    p.font.size = Pt(size)
    p.font.color.rgb = color


def add_bullets(slide, items: list[str], top=Inches(1.5), left=Inches(0.6), width=None, size=18) -> None:
    width = width or (SLIDE_W - Inches(1.2))
    box = slide.shapes.add_textbox(left, top, width, SLIDE_H - top - Inches(0.4))
    tf = box.text_frame
    tf.word_wrap = True
    for i, item in enumerate(items):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = f"•  {item}"
        p.font.size = Pt(size)
        p.font.color.rgb = GRAY
        p.space_after = Pt(10)


def add_picture_centered(slide, path: Path, top=Inches(1.5), max_height=Inches(5.5)) -> None:
    if not path.exists():
        return
    pic = slide.shapes.add_picture(str(path), Inches(0), top, height=max_height)
    pic.left = int((SLIDE_W - pic.width) / 2)


def title_slide(prs, title: str, subtitle: str) -> None:
    slide = blank_slide(prs)
    slide.background.fill.solid()
    slide.background.fill.fore_color.rgb = NAVY
    box = slide.shapes.add_textbox(Inches(0.8), Inches(2.6), SLIDE_W - Inches(1.6), Inches(1.5))
    p = box.text_frame.paragraphs[0]
    p.text = title
    p.font.size = Pt(40)
    p.font.bold = True
    p.font.color.rgb = WHITE
    box2 = slide.shapes.add_textbox(Inches(0.8), Inches(4.0), SLIDE_W - Inches(1.6), Inches(1.0))
    p2 = box2.text_frame.paragraphs[0]
    p2.text = subtitle
    p2.font.size = Pt(20)
    p2.font.color.rgb = RGBColor(0xCC, 0xD6, 0xE0)


def content_slide(prs, title: str, bullets: list[str], subtitle: str | None = None) -> None:
    slide = blank_slide(prs)
    add_title(slide, title)
    top = Inches(1.2)
    if subtitle:
        add_subtitle(slide, subtitle)
        top = Inches(1.8)
    add_bullets(slide, bullets, top=top)


def figure_slide(prs, title: str, figure_name: str, caption: str | None = None) -> None:
    slide = blank_slide(prs)
    add_title(slide, title, size=26)
    add_picture_centered(slide, FIGURES / figure_name, top=Inches(1.1))
    if caption:
        box = slide.shapes.add_textbox(Inches(0.6), SLIDE_H - Inches(0.6), SLIDE_W - Inches(1.2), Inches(0.5))
        p = box.text_frame.paragraphs[0]
        p.text = caption
        p.font.size = Pt(13)
        p.font.italic = True
        p.font.color.rgb = GRAY
        p.alignment = PP_ALIGN.CENTER


