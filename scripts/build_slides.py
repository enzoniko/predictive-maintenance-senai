def main() -> None:
    cfg = load_config()
    bundle = ModelBundle.load(cfg.paths.models_dir / BUNDLE_FILENAME)
    build_executive_deck(bundle)
    build_technical_deck(bundle)


if __name__ == "__main__":
    main()
