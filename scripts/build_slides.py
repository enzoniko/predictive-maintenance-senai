    figure_slide(prs, "Calibração de probabilidade", "calibration.png",
                 "ECE baixo é pré-requisito para a predição conformal fazer sentido.")

    figure_slide(prs, "Predição conformal: tamanho do conjunto de predição", "conformal_set_sizes.png")

